"""自包含的成员来源统计，背景与底部信息卡均在内存绘制。"""

import io
import math
import os
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont, ImageOps

_WIDTH, _HEIGHT = 960, 1320
_MARGIN, _BOTTOM = 48, 76
_BAR_COLOR = (91, 155, 213)


def summarize(records: dict) -> list[tuple[str, int]]:
    counts = {}
    for record in records.values():
        if isinstance(record, dict) and "source_category" in record:
            category = record["source_category"]
            if not isinstance(category, str) or not category.strip():
                continue
        else:
            category = record.get("category") if isinstance(record, dict) else None
        category = category.strip() if isinstance(category, str) else ""
        category = category or "未知"
        counts[category] = counts.get(category, 0) + 1
    return sorted(counts.items(), key=lambda item: (-item[1], item[0]))


def _font(size: int, font_path: str):
    candidates = [
        font_path,
        str(Path(os.environ.get("WINDIR", "C:/Windows")) / "Fonts/msyh.ttc"),
        "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc",
        "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
        "DejaVuSans.ttf",
    ]
    for path in candidates:
        if path:
            try:
                return ImageFont.truetype(path, size=size)
            except (OSError, ValueError):
                pass
    return ImageFont.load_default(size=size)


def _wrap(text: str, font, width: float) -> list[str]:
    lines = []
    for paragraph in text.split("\n"):
        line = ""
        for char in paragraph:
            if line and font.getlength(line + char) > width:
                lines.append(line)
                line = ""
            line += char
        lines.append(line)
    return lines


def _layout(gid, summary, font_path):
    inner_width = _WIDTH - 2 * (_MARGIN + 32)
    total = sum(count for _, count in summary)
    for size in range(24, 5, -1):
        label_font = _font(size, font_path)
        title_font = _font(max(20, round(size * 1.4)), font_path)
        info_font = _font(max(12, size - 3), font_path)
        number_font = _font(max(8, size - 2), font_path)
        title_lines = _wrap(f"群 {gid} · 成员来源统计", title_font, inner_width)
        info_lines = _wrap(f"已记录成员 {total} 人  ·  {len(summary)} 类来源", info_font, inner_width)
        title_height = math.ceil(title_font.size * 1.35)
        info_height = math.ceil(info_font.size * 1.4)
        line_height = math.ceil(size * 1.4)
        bar_height = max(5, round(size * 0.65))
        gap = max(3, round(size * 0.32))
        row_gap = max(5, round(size * 0.75))
        rows = []
        for category, count in summary:
            number = f"{count} 人"
            label_width = inner_width - number_font.getlength(number) - 24
            lines = _wrap(category, label_font, label_width)
            height = len(lines) * line_height + gap + bar_height + row_gap
            rows.append((lines, number, count, height))
        content_height = (
            32 + len(title_lines) * title_height + 10
            + len(info_lines) * info_height + 24
            + (sum(row[3] for row in rows) if rows else 120)
            + info_height + 24
        )
        if content_height <= _HEIGHT - _BOTTOM - _MARGIN:
            return {
                "label_font": label_font, "title_font": title_font,
                "info_font": info_font, "number_font": number_font,
                "title_lines": title_lines, "info_lines": info_lines,
                "title_height": title_height, "info_height": info_height,
                "line_height": line_height, "bar_height": bar_height,
                "gap": gap, "rows": rows, "height": max(594, content_height),
            }
    # 固定画布不能容纳无限内容，明确报错而不是静默丢弃分类。
    raise ValueError("分类文字过多，无法在固定统计图中完整显示")


def _draw_watermark(canvas: Image.Image, font_path: str) -> None:
    text = "©PL!HS ©S ©2023 BNML ©ODD No. Generated by KhBot"
    font = _font(27, font_path)
    draw = ImageDraw.Draw(canvas)
    position = (893, 1280)
    bounds = draw.textbbox(position, text, font=font, anchor="rb", stroke_width=1)
    sample = canvas.crop(bounds).convert("RGB").resize((64, 8))
    pixels = [sample.getpixel((x, y)) for y in range(sample.height) for x in range(sample.width)]
    # 仅采样水印下面的实际背景，按相对亮度比较深浅色对比度。
    linear = [(value / 255 / 12.92 if value <= 10 else ((value / 255 + 0.055) / 1.055) ** 2.4)
              for value in range(256)]
    luminance = sum(0.2126 * linear[r] + 0.7152 * linear[g] + 0.0722 * linear[b]
                    for r, g, b in pixels) / (64 * 8)
    dark, light = linear[51], linear[245]
    dark_contrast = (max(luminance, dark) + 0.05) / (min(luminance, dark) + 0.05)
    light_contrast = (max(luminance, light) + 0.05) / (min(luminance, light) + 0.05)
    fill, outline = ("#333333", "#F5F5F5") if dark_contrast >= light_contrast else ("#F5F5F5", "#333333")
    # 细反色描边照顾花纹背景；保留原文字、字号和右下角位置。
    draw.text(position, text, font=font, fill=fill, anchor="rb", stroke_width=1, stroke_fill=outline)


def render_chart(gid, records: dict, *, font_path: str = "", background_path: str = "") -> bytes:
    summary = summarize(records)
    layout = _layout(gid, summary, font_path)
    canvas = Image.new("RGBA", (_WIDTH, _HEIGHT), (241, 244, 248, 255))
    if background_path:
        try:
            with Image.open(background_path) as background:
                canvas.alpha_composite(ImageOps.fit(
                    background.convert("RGBA"), canvas.size, method=Image.Resampling.LANCZOS,
                ))
        except (OSError, ValueError):
            pass

    card_top = _HEIGHT - _BOTTOM - layout["height"]
    card_right = _WIDTH - _MARGIN
    overlay = Image.new("RGBA", canvas.size)
    ImageDraw.Draw(overlay).rounded_rectangle(
        (_MARGIN, card_top, card_right, _HEIGHT - _BOTTOM), radius=28,
        fill=(255, 255, 255, 226), outline=(218, 225, 234, 235), width=1,
    )
    canvas = Image.alpha_composite(canvas, overlay)
    draw = ImageDraw.Draw(canvas)
    left, right = _MARGIN + 32, card_right - 32
    y = card_top + 32
    for line in layout["title_lines"]:
        draw.text((left, y), line, font=layout["title_font"], fill="#263445", anchor="lt")
        y += layout["title_height"]
    y += 10
    for line in layout["info_lines"]:
        draw.text((left, y), line, font=layout["info_font"], fill="#677584", anchor="lt")
        y += layout["info_height"]
    y += 24
    if not summary:
        draw.text((left, y + 32), "暂无成员来源记录", font=layout["label_font"], fill="#677584", anchor="lt")
        y += 120
    else:
        max_count = summary[0][1]
        for lines, number, count, row_height in layout["rows"]:
            row_top = y
            for line in lines:
                draw.text((left, y), line, font=layout["label_font"], fill="#334155", anchor="lt")
                y += layout["line_height"]
            draw.text((right, row_top), number, font=layout["number_font"], fill="#526170", anchor="rt")
            y += layout["gap"]
            bottom = y + layout["bar_height"] - 1
            draw.rectangle((left, y, right - 1, bottom), fill="#E6ECF3")
            bar_width = max(1, round((right - left) * count / max_count))
            draw.rectangle((left, y, left + bar_width - 1, bottom), fill=_BAR_COLOR)
            y = row_top + row_height
    draw.text((left, y), "仅统计当前保留的来源记录", font=layout["info_font"], fill="#8491A1", anchor="lt")
    _draw_watermark(canvas, font_path)
    output = io.BytesIO()
    canvas.convert("RGB").save(output, format="PNG")
    return output.getvalue()
